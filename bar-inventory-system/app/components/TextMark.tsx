import type { HTMLAttributes } from 'react';

// Text labels keep actions readable without an icon library.
function mark(label: string) {
  return function TextMark({ className, size, ...props }: HTMLAttributes<HTMLSpanElement> & { size?: number }) {
    if (!label) return null;
    return <span {...props} className="action-word">{label}</span>;
  };
}
